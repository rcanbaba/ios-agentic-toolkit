#!/usr/bin/env python3
"""Generate SwiftUI design tokens and a specimen view from a design-system contract.

Deterministic step of the design-system workflow. The contract is the source
of truth; generated files must not be edited by hand.

Outputs (in --out):
  DesignTokens.swift           DS namespace: colors (light/dark), spacing, radii,
                               shapes, shadows, borders, components; DSTextStyle
                               with Dynamic Type scaling; .dsFont / .dsComponent
  DesignSystemSpecimen.swift   Specimen view with Light / Dark / large-type previews

Usage: generate_swiftui.py <design-system.json> --out <dir> [--check]
  --check   typecheck the output against the iOS Simulator SDK (needs Xcode)
Exit code 0 = generated, 1 = invalid contract or failed typecheck, 2 = usage/IO error.
"""

import json
import subprocess
import sys
from pathlib import Path

from schema_lite import check_schema
from validate_design_system import DEFAULT_SCHEMA, check_semantics

HEADER = """// Generated by ios-agentic-toolkit from design-system.json ("{name}").
// Do not edit by hand: change the contract and regenerate.
"""


def rgba(hex_value):
    v = hex_value.lstrip("#").upper()
    if len(v) == 6:
        v += "FF"
    return f"0x{v}"


def num(value):
    return f"{value:g}"


def swift_string(value):
    return json.dumps(value, ensure_ascii=False)


def role_color(doc, role):
    return next(c["name"] for c in doc["colors"] if c["role"] == role)


def tokens_swift(doc):
    out = [HEADER.format(name=doc["name"]), "import SwiftUI", "import UIKit", "", "enum DS {"]

    out.append("    enum Colors {")
    for c in doc["colors"]:
        origin = c["origin"] + (f" ({c['reference']})" if c.get("reference") else "")
        out.append(f"        /// {c['role']} · {origin}")
        out.append(f"        static let {c['name']} = Color(dsLight: {rgba(c['light'])}, dark: {rgba(c['dark'])})")
    out.append("    }")
    out.append("")

    out.append("    enum Spacing {")
    for s in doc["spacing"]:
        out.append(f"        static let {s['name']}: CGFloat = {num(s['value'])}")
    out.append("    }")
    out.append("")

    out.append("    enum Radius {")
    for r in doc["radii"]:
        out.append(f"        static let {r['name']}: CGFloat = {num(r['value'])}")
    out.append("    }")
    out.append("")

    out.append("    enum Shapes {")
    for r in doc["radii"]:
        out.append(f"        static let {r['name']} = RoundedRectangle(cornerRadius: Radius.{r['name']}, style: .{r['style']})")
    out.append("    }")
    out.append("")

    out.append("    enum Shadows {")
    for s in doc["shadows"]:
        out.append(
            f"        static let {s['name']} = DSShadow(color: Colors.{s['color']}, opacity: {num(s['opacity'])}, "
            f"radius: {num(s['radius'])}, x: {num(s['x'])}, y: {num(s['y'])})"
        )
    out.append("    }")
    out.append("")

    out.append("    enum Borders {")
    for b in doc["borders"]:
        out.append(f"        static let {b['name']} = DSBorder(width: {num(b['width'])}, color: Colors.{b['color']})")
    out.append("    }")
    out.append("")

    radius_styles = {r["name"]: r["style"] for r in doc["radii"]}
    out.append("    enum Components {")
    for c in doc["components"]:
        border = f"Borders.{c['border']}" if c.get("border") else "nil"
        shadow = f"Shadows.{c['shadow']}" if c.get("shadow") else "nil"
        out.append(f"        /// {c['notes']}" if c["notes"] else "        ///")
        out.append(
            f"        static let {c['name']} = DSComponent(\n"
            f"            background: Colors.{c['background']}, foreground: Colors.{c['foreground']},\n"
            f"            textStyle: .{c['text_style']}, radius: Radius.{c['radius']}, radiusStyle: .{radius_styles[c['radius']]},\n"
            f"            paddingH: Spacing.{c['padding_h']}, paddingV: Spacing.{c['padding_v']},\n"
            f"            border: {border}, shadow: {shadow}, minHeight: {num(c.get('min_height', 0))})"
        )
    out.append("    }")
    out.append("}")
    out.append("")

    families = {f["id"]: f for f in doc["typography"]["families"]}
    styles = doc["typography"]["styles"]
    out.append("enum DSTextStyle: String, CaseIterable {")
    out.append("    case " + ", ".join(s["name"] for s in styles))
    out.append("")

    def switch(prop, type_name, value_fn):
        out.append(f"    var {prop}: {type_name} {{")
        out.append("        switch self {")
        for s in styles:
            out.append(f"        case .{s['name']}: {value_fn(s)}")
        out.append("        }")
        out.append("    }")
        out.append("")

    switch("size", "CGFloat", lambda s: num(s["size"]))
    switch("relativeTo", "Font.TextStyle", lambda s: f".{s['relative_to']}")
    switch("tracking", "CGFloat", lambda s: num(s.get("tracking", 0)))
    switch("lineSpacing", "CGFloat", lambda s: num(s.get("line_spacing", 0)))
    switch("weightName", "String", lambda s: swift_string(s["weight"]))

    def font_expr(s):
        family = families[s["family"]]
        if family["kind"] == "bundled":
            return f".custom({swift_string(s['postscript_name'])}, fixedSize: size)"
        design = family.get("system_design", "default")
        return f".system(size: size, weight: .{s['weight']}, design: .{design})"

    out.append("    func font(size: CGFloat) -> Font {")
    out.append("        switch self {")
    for s in styles:
        out.append(f"        case .{s['name']}: {font_expr(s)}")
    out.append("        }")
    out.append("    }")
    out.append("}")

    out.append("""
struct DSShadow {
    let color: Color
    let opacity: Double
    let radius: CGFloat
    let x: CGFloat
    let y: CGFloat
}

struct DSBorder {
    let width: CGFloat
    let color: Color
}

struct DSComponent {
    let background: Color
    let foreground: Color
    let textStyle: DSTextStyle
    let radius: CGFloat
    let radiusStyle: RoundedCornerStyle
    let paddingH: CGFloat
    let paddingV: CGFloat
    let border: DSBorder?
    let shadow: DSShadow?
    let minHeight: CGFloat
}

private struct DSTextStyleModifier: ViewModifier {
    @ScaledMetric private var size: CGFloat
    private let style: DSTextStyle

    init(_ style: DSTextStyle) {
        self.style = style
        _size = ScaledMetric(wrappedValue: style.size, relativeTo: style.relativeTo)
    }

    func body(content: Content) -> some View {
        content
            .font(style.font(size: size))
            .tracking(style.tracking)
            .lineSpacing(style.lineSpacing)
    }
}

private struct DSComponentModifier: ViewModifier {
    let component: DSComponent

    func body(content: Content) -> some View {
        let shape = RoundedRectangle(cornerRadius: component.radius, style: component.radiusStyle)
        content
            .dsFont(component.textStyle)
            .foregroundStyle(component.foreground)
            .padding(.horizontal, component.paddingH)
            .padding(.vertical, component.paddingV)
            .frame(minHeight: component.minHeight)
            .background(component.background, in: shape)
            .overlay {
                if let border = component.border {
                    shape.strokeBorder(border.color, lineWidth: border.width)
                }
            }
            .dsShadow(component.shadow)
    }
}

extension View {
    /// Applies a design-system text style; size scales with Dynamic Type.
    func dsFont(_ style: DSTextStyle) -> some View {
        modifier(DSTextStyleModifier(style))
    }

    func dsShadow(_ token: DSShadow?) -> some View {
        shadow(
            color: token.map { $0.color.opacity($0.opacity) } ?? .clear,
            radius: token?.radius ?? 0,
            x: token?.x ?? 0,
            y: token?.y ?? 0
        )
    }

    /// Applies a full component recipe: text style, colors, padding, shape, border, shadow.
    func dsComponent(_ component: DSComponent) -> some View {
        modifier(DSComponentModifier(component: component))
    }
}

extension Color {
    /// Dynamic color from 0xRRGGBBAA values for light and dark appearance.
    init(dsLight light: UInt32, dark: UInt32) {
        self.init(uiColor: UIColor { traits in
            UIColor(dsRGBA: traits.userInterfaceStyle == .dark ? dark : light)
        })
    }
}

private extension UIColor {
    convenience init(dsRGBA value: UInt32) {
        self.init(
            red: CGFloat((value >> 24) & 0xFF) / 255,
            green: CGFloat((value >> 16) & 0xFF) / 255,
            blue: CGFloat((value >> 8) & 0xFF) / 255,
            alpha: CGFloat(value & 0xFF) / 255
        )
    }
}""")
    return "\n".join(out) + "\n"


def specimen_swift(doc):
    bg = role_color(doc, "background")
    text = role_color(doc, "text_primary")
    secondary = role_color(doc, "text_secondary")
    surface = role_color(doc, "surface")

    colors = ",\n".join(
        f"        ({swift_string(c['name'])}, {swift_string(c['role'])}, {swift_string(c['light'].upper() + ' / ' + c['dark'].upper())}, DS.Colors.{c['name']})"
        for c in doc["colors"]
    )
    spacing = ",\n".join(f"        ({swift_string(s['name'])}, DS.Spacing.{s['name']})" for s in doc["spacing"])
    radii = ",\n".join(f"        ({swift_string(r['name'])}, DS.Radius.{r['name']}, DS.Shapes.{r['name']})" for r in doc["radii"])
    shadows = ",\n".join(f"        ({swift_string(s['name'])}, DS.Shadows.{s['name']})" for s in doc["shadows"])
    components = ",\n".join(f"        ({swift_string(c['name'])}, DS.Components.{c['name']})" for c in doc["components"])
    signature = "\n".join(f"                Text({swift_string('• ' + s)})" for s in doc["signature"])

    return HEADER.format(name=doc["name"]) + f"""
import SwiftUI

/// Scrollable specimen for Xcode previews and debug screens.
struct DesignSystemSpecimen: View {{
    var body: some View {{
        ScrollView {{
            DesignSystemSpecimenContent()
        }}
        .background(DS.Colors.{bg})
    }}
}}

/// Non-scrolling specimen content; also used for rendering PNG snapshots.
struct DesignSystemSpecimenContent: View {{
    private let colors: [(String, String, String, Color)] = [
{colors}
    ]
    private let spacing: [(String, CGFloat)] = [
{spacing}
    ]
    private let radii: [(String, CGFloat, RoundedRectangle)] = [
{radii}
    ]
    private let shadows: [(String, DSShadow)] = [
{shadows}
    ]
    private let components: [(String, DSComponent)] = [
{components}
    ]

    var body: some View {{
        VStack(alignment: .leading, spacing: 32) {{
            VStack(alignment: .leading, spacing: 8) {{
                Text({swift_string(doc["name"])}).font(.largeTitle.bold())
                Text({swift_string(doc["summary"])})
                    .font(.callout)
                    .foregroundStyle(DS.Colors.{secondary})
            }}

            section("Signature") {{
{signature}
            }}
            .font(.callout)

            section("Colors") {{
                ForEach(colors, id: \\.0) {{ name, role, hex, color in
                    HStack(spacing: 12) {{
                        RoundedRectangle(cornerRadius: 10, style: .continuous)
                            .fill(color)
                            .frame(width: 48, height: 48)
                            .overlay(RoundedRectangle(cornerRadius: 10, style: .continuous).strokeBorder(.gray.opacity(0.3)))
                        VStack(alignment: .leading, spacing: 2) {{
                            Text(name).font(.callout.weight(.semibold))
                            Text("\\(role) · \\(hex)").font(.caption.monospaced()).foregroundStyle(DS.Colors.{secondary})
                        }}
                    }}
                }}
            }}

            section("Typography") {{
                ForEach(DSTextStyle.allCases, id: \\.self) {{ style in
                    VStack(alignment: .leading, spacing: 4) {{
                        Text("The quick brown fox jumps over the lazy dog").dsFont(style)
                        Text("Ağaç çiçek ışık öğün şüphe İĞÜŞÖÇ 0123456789").dsFont(style)
                        Text("\\(style.rawValue) · \\(Int(style.size))pt · \\(style.weightName) · scales with \\(String(describing: style.relativeTo))")
                            .font(.caption.monospaced())
                            .foregroundStyle(DS.Colors.{secondary})
                    }}
                }}
            }}

            section("Spacing") {{
                ForEach(spacing, id: \\.0) {{ name, value in
                    HStack(spacing: 12) {{
                        Rectangle().fill(DS.Colors.{text}.opacity(0.6)).frame(width: value, height: 16)
                        Text("\\(name) · \\(Int(value))").font(.caption.monospaced())
                    }}
                }}
            }}

            section("Radii") {{
                LazyVGrid(columns: [GridItem(.adaptive(minimum: 96))], alignment: .leading, spacing: 16) {{
                    ForEach(radii, id: \\.0) {{ name, value, shape in
                        VStack(spacing: 6) {{
                            shape.fill(DS.Colors.{surface}).frame(width: 88, height: 64)
                                .overlay(shape.strokeBorder(DS.Colors.{text}.opacity(0.25)))
                            Text("\\(name) · \\(Int(value))").font(.caption.monospaced())
                        }}
                    }}
                }}
            }}

            if !shadows.isEmpty {{
                section("Shadows") {{
                    ForEach(shadows, id: \\.0) {{ name, token in
                        Text(name)
                            .font(.callout)
                            .frame(maxWidth: .infinity, minHeight: 72)
                            .background(DS.Colors.{surface}, in: RoundedRectangle(cornerRadius: 12, style: .continuous))
                            .dsShadow(token)
                    }}
                }}
            }}

            if !components.isEmpty {{
                section("Components") {{
                    ForEach(components, id: \\.0) {{ name, component in
                        Text(name).dsComponent(component)
                    }}
                }}
            }}
        }}
        .padding(20)
        .frame(maxWidth: .infinity, alignment: .leading)
        .foregroundStyle(DS.Colors.{text})
        .background(DS.Colors.{bg})
    }}

    private func section<Content: View>(_ title: String, @ViewBuilder content: () -> Content) -> some View {{
        VStack(alignment: .leading, spacing: 12) {{
            Text(title.uppercased())
                .font(.caption.weight(.semibold))
                .foregroundStyle(DS.Colors.{secondary})
            content()
        }}
    }}
}}

#Preview("Light") {{
    DesignSystemSpecimen()
        .preferredColorScheme(.light)
}}

#Preview("Dark") {{
    DesignSystemSpecimen()
        .preferredColorScheme(.dark)
}}

#Preview("Large type") {{
    DesignSystemSpecimen()
        .environment(\\.dynamicTypeSize, .accessibility2)
}}
"""


def typecheck(files):
    cmd = [
        "xcrun", "--sdk", "iphonesimulator", "swiftc", "-typecheck",
        "-target", "arm64-apple-ios17.0-simulator", *map(str, files),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    return result.returncode == 0, (result.stdout + result.stderr).strip()


def main(argv):
    args = argv[1:]
    check = "--check" in args
    if check:
        args.remove("--check")
    if "--out" not in args:
        print("usage: generate_swiftui.py <design-system.json> --out <dir> [--check]", file=sys.stderr)
        return 2
    i = args.index("--out")
    out_dir = Path(args[i + 1])
    del args[i:i + 2]
    if len(args) != 1:
        print("usage: generate_swiftui.py <design-system.json> --out <dir> [--check]", file=sys.stderr)
        return 2
    try:
        schema = json.loads(DEFAULT_SCHEMA.read_text())
        doc = json.loads(Path(args[0]).read_text())
    except (OSError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    errors, warnings = [], []
    check_schema(doc, schema, "$", errors)
    if not errors:
        check_semantics(doc, errors, warnings)
    if errors:
        print("Contract is invalid; run validate_design_system.py for details. Nothing generated.")
        for e in errors:
            print(f"  - error: {e}")
        return 1

    out_dir.mkdir(parents=True, exist_ok=True)
    files = [out_dir / "DesignTokens.swift", out_dir / "DesignSystemSpecimen.swift"]
    files[0].write_text(tokens_swift(doc))
    files[1].write_text(specimen_swift(doc))
    for f in files:
        print(f"wrote {f}")
    for w in warnings:
        print(f"  - warning: {w}")

    if check:
        ok, output = typecheck(files)
        print("typecheck: " + ("passed" if ok else "FAILED"))
        if output:
            print(output)
        return 0 if ok else 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
