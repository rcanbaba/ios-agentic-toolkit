#!/usr/bin/env python3
"""Render the per-flow section of PENDING_DECISIONS.md from the flow specs.

Deterministic step of the flow-spec skill. The cross-cutting rules (A) and the default
rule (B) are written by the orchestrator; the flow-specific questions (C) are generated
here from every open_decisions entry that is still open: no decision, or a decision
that defers it ("defer to porting; ..."). A decided question is never listed again.

The generated block sits between these markers and is replaced on every run; the rest
of the file is kept. Without the markers, the block is appended.
  <!-- BEGIN per-flow questions (generated by render_pending.py) -->
  <!-- END per-flow questions -->

Usage: render_pending.py <PENDING_DECISIONS.md> <spec.json>...
Exit code 0 = written, 2 = usage/IO error.
"""

import json
import re
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN per-flow questions (generated by render_pending.py) -->"
END = "<!-- END per-flow questions -->"


def still_open(decision):
    text = (decision.get("decision") or "").strip()
    return not text or text.lower().startswith("defer")


def block(specs):
    lines = [BEGIN, ""]
    total = 0
    for spec in sorted(specs, key=lambda s: s["flow_id"]):
        items = [d for d in spec["open_decisions"] if still_open(d)]
        if not items:
            continue
        total += len(items)
        lines += [f"### {spec['flow_id']} ({len(items)})", ""]
        for d in items:
            rule = f" [rule {d['rule']}]" if d.get("rule") else ""
            lines.append(f"- {d['id']} {d['question']} (current: {d['current_behavior']}){rule}")
        lines.append("")
    if not total:
        lines += ["No open flow-specific questions.", ""]
    return "\n".join(lines + [END]), total


def main(argv):
    if len(argv) < 3:
        print("usage: render_pending.py <PENDING_DECISIONS.md> <spec.json>...", file=sys.stderr)
        return 2
    out = Path(argv[1])
    try:
        specs = [json.loads(Path(p).read_text()) for p in argv[2:]]
        current = out.read_text() if out.is_file() else "# Pending decisions from flow specs\n"
    except (OSError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    generated, total = block(specs)
    if BEGIN in current and END in current:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: generated, current, flags=re.S)
    else:
        text = current.rstrip() + "\n\n" + generated + "\n"
    out.write_text(text)
    print(f"wrote {out}: {total} open flow-specific question(s) across {len(specs)} spec(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
